import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const dir=path.resolve(process.argv[2]??'');
if(!process.argv[2])throw Error('Supply GUI evidence directory');
const bytes=p=>fs.readFileSync(p),hash=b=>crypto.createHash('sha256').update(b).digest('hex');
const read=p=>JSON.parse(bytes(p).toString().replace(/^\uFEFF/,''));
const state=read(path.join(dir,'states.json')),run=read(state.run),build=read(state.build);
if(!build.passed||run.buildSummarySha256!==hash(bytes(state.build)))throw Error('Build/run identity');
for(const s of build.sources)if(hash(bytes(path.join(build.sourceRoot,s.path)))!==s.sha256)throw Error('Frozen source drift');
const before=bytes(path.join(dir,'before.dls')),scaled=bytes(path.join(dir,'scaled.dls'));
const nativeBase=path.join(path.dirname(state.run),'core/dls-editor');
const nativeProof=read(path.join(nativeBase,'editor-proof.json'));
if(hash(before)!==run.referenceCollection.sha256||hash(scaled)!==nativeProof.ownedScaledSha256)throw Error('PCM expectation');
if(!bytes(path.join(dir,'undo.dls')).equals(before)||!bytes(path.join(dir,'redo.dls')).equals(scaled)||!bytes(path.join(dir,'owned.dls')).equals(scaled))throw Error('GUI history/save bytes');
const captures=state.records.map(r=>({...r,imageSha256:hash(bytes(path.join(dir,r.image)))}));
if(new Set(captures.map(r=>r.imageSha256)).size!==captures.length)throw Error('Repeated capture');
const exe=run.cases.find(c=>c.name==='host-smoke');
if(!captures.every(r=>r.window.app.includes(path.dirname(state.build).replaceAll('/','\\'))))throw Error('GUI executable path');
const closed=read(path.join(dir,'closed-windows.json'));
if(closed.some(w=>w.app===captures[0].window.app))throw Error('GUI still open');
const proof={schema:1,build:state.build,buildSha256:hash(bytes(state.build)),run:state.run,runSha256:hash(bytes(state.run)),exeSha256:exe.sha256,sourceCount:build.sources.length,beforeSha256:hash(before),scaledSha256:hash(scaled),guiPcmHalfAndUndoRedoSaveAllBytes:true,captures,closedWindowObserved:true,guiExitCode:'unverified',keyboardInput:state.keyboardInput,restartReload:'unexecuted',guiInstrumentRegionEdits:'unverified',guiModuleInventory:'unverified',fullAcceptance:false,auditorSha256:hash(bytes(new URL(import.meta.url)))};
fs.writeFileSync(path.join(dir,'wave-unit-audit.json'),JSON.stringify(proof,null,2)+'\n');
fs.copyFileSync(new URL(import.meta.url),path.join(dir,'wave-auditor.mjs'));
console.log(JSON.stringify({passed:true,captures:captures.length,proof:path.join(dir,'wave-unit-audit.json')}));
