import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
const dir=path.resolve(process.argv[2]),first=path.resolve(process.argv[3]);
const json=p=>JSON.parse(fs.readFileSync(p,'utf8').replace(/^\uFEFF/,''));
const hash=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const launch=json(dir+'/launch.json'),prior=json(first+'/variation-gui-proof.json'),records=json(dir+'/variation-states.json');
assert(launch.passed&&launch.exitCode===0&&!launch.timedOut&&prior.passed);
assert.notEqual(launch.processId,prior.processId);
assert.equal(launch.exeSha256,prior.productExeSha256);
assert.equal(hash(launch.executable),launch.exeSha256);
assert.equal(hash(launch.buildSummary),launch.buildSummarySha256);
const input=launch.inputs.find(i=>path.basename(i.path)==='Heartlnd.stp');
assert.equal(input.sha256,prior.savedStyleSha256);
assert.equal(hash(first+'/gui-saved.stp'),input.sha256);
assert.equal(hash(dir+'/resaved.stp'),input.sha256);
for(const i of launch.inputs)assert.equal(hash(i.path),i.sha256);
for(const r of records)for(const c of r.captures)assert.equal(hash(dir+'/'+c.file),c.sha256);
const tree=label=>{const r=records.find(r=>r.label===label);assert(r&&r.captures.length);return r.accessibility?.tree??'';};
assert(tree('reload-first-ready').includes('Variation 1 ID: 705'));
assert(tree('reload-first-ready').includes('109 編集 (settable, string) Value: 127'));
assert(tree('reload-last').includes('Variation 32 ID: 705'));
assert(tree('reload-last').includes('109 編集 (settable, string) Value: 2435007847'));
assert(tree('reload-before-close').includes('Variation 32 ID: 705'));
const modules=json(dir+'/gui-module-provenance.json');assert(modules.passed);assert.equal(modules.exeSha256,launch.exeSha256);
assert.equal(json(dir+'/gui-modules.json').processId,launch.processId);
const state=json(dir+'/states.json');state.records=records.map(r=>({...r,screenshots:r.captures}));
fs.writeFileSync(dir+'/states.json',JSON.stringify(state,null,2)+'\n');
const proof={schema:1,passed:true,productBuild:launch.buildSummary,productExeSha256:launch.exeSha256,firstProcessId:prior.processId,processId:launch.processId,normalExitCode:0,savedStyleSha256:input.sha256,statesSha256:hash(dir+'/states.json'),firstProofSha256:hash(first+'/variation-gui-proof.json'),moduleProofSha256:hash(dir+'/gui-module-provenance.json'),auditorSha256:hash(process.argv[1]),scope:'Same-build separate PID reload of first GUI save, Variation1=127 and Variation32=0x91234567, byte-identical resave; no GUI playback/original/full acceptance claim',fullAcceptance:false};
fs.copyFileSync(process.argv[1],dir+'/variation-gui-reload-auditor.mjs');
fs.writeFileSync(dir+'/variation-gui-reload-proof.json',JSON.stringify(proof,null,2)+'\n');
console.log(JSON.stringify(proof));
